-- Libro de guardia legible: cada contacto con su banda, modo, país y estado de QSL.
CREATE VIEW vista_libro_guardia AS
SELECT
    c.id,
    u.indicativo                                       AS operador,
    c.estacion_llamada,
    p.pais,
    c.inicio_utc,
    c.fin_utc,
    c.frecuencia_mhz,
    b.nombre                                           AS banda,
    m.nombre                                           AS modo,
    c.reporte_enviado,
    c.reporte_recibido,
    CASE
        WHEN bool_or(q.recibida) THEN 'confirmado'
        WHEN bool_or(q.enviada)  THEN 'enviada'
        ELSE 'pendiente'
    END                                                AS estado_qsl,
    coalesce(bool_or(q.tipo = 'interna'), false)       AS confirmado_automaticamente
FROM contactos c
JOIN users u          ON u.id = c.user_id
JOIN bandas b         ON b.id = c.banda_id
JOIN modos m          ON m.id = c.modo_id
LEFT JOIN prefijos_pais p      ON p.id = c.prefijo_pais_id
LEFT JOIN confirmaciones_qsl q ON q.contacto_id = c.id
GROUP BY c.id, u.indicativo, p.pais, b.nombre, m.nombre;

COMMENT ON VIEW vista_libro_guardia IS 'Contactos con sus catálogos y el estado de QSL calculado.';


-- Solicitudes de confirmación: contactos que OTRA estación anotó con un operador registrado
-- y que ese operador todavía no tiene en su libro (no tienen QSL interna) ni rechazó.
-- La unión es por indicativo (estacion_llamada = users.indicativo), no por llave foránea.
CREATE VIEW vista_solicitudes_pendientes AS
SELECT
    destinatario.indicativo AS para_operador,
    autor.indicativo        AS de_estacion,
    c.id                    AS contacto_id,
    c.inicio_utc,
    b.nombre                AS banda,
    m.nombre                AS modo
FROM contactos c
JOIN users autor        ON autor.id = c.user_id
JOIN users destinatario ON destinatario.indicativo = c.estacion_llamada
                       AND destinatario.id <> c.user_id
JOIN bandas b ON b.id = c.banda_id
JOIN modos m  ON m.id = c.modo_id
WHERE c.rechazado_por_contraparte_at IS NULL
  AND NOT EXISTS (
      SELECT 1 FROM confirmaciones_qsl q
      WHERE q.contacto_id = c.id AND q.tipo = 'interna'
  );

COMMENT ON VIEW vista_solicitudes_pendientes IS 'Solicitudes de confirmación pendientes por operador (innovación 1).';

