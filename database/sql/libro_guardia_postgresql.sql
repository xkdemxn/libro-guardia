-- =============================================================================
--  LIBRO DE GUARDIA — Sistema web para radioaficionados
--  Estructura de la base de datos en PostgreSQL (para pgAdmin 4)
--
--  Equivale a las migraciones de Laravel del proyecto (que corre en MariaDB).
--  Cómo usarlo en pgAdmin 4:
--    1. Crea una base de datos vacía, por ejemplo "libro_guardia".
--    2. Abre la Query Tool sobre esa base, pega este archivo y ejecútalo (F5).
--    3. Para ver el diagrama: clic derecho en la base → "ERD For Database".
-- =============================================================================

BEGIN;

DROP TABLE IF EXISTS confirmaciones_qsl, contactos, visibilidad_perfil, prefijos_pais, modos, bandas, users CASCADE;


-- -----------------------------------------------------------------------------
--  1. USERS — el operador (radioaficionado registrado)
-- -----------------------------------------------------------------------------
CREATE TABLE users (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicativo         varchar(20)  NOT NULL,
    nombres            varchar(100) NOT NULL,
    apellidos          varchar(100) NOT NULL,
    pais               varchar(100),
    ciudad             varchar(100),
    grid_locator       varchar(8),
    equipo_radio       varchar(255),
    antena             varchar(255),
    biografia          text,
    foto_path          varchar(255),
    email              varchar(255) NOT NULL,
    email_verified_at  timestamp,
    password           varchar(255) NOT NULL,
    remember_token     varchar(100),
    created_at         timestamp,
    updated_at         timestamp,
    CONSTRAINT users_indicativo_unique UNIQUE (indicativo),
    CONSTRAINT users_email_unique      UNIQUE (email),
    -- El indicativo se guarda siempre en mayúsculas y sin espacios.
    CONSTRAINT users_indicativo_formato CHECK (indicativo = upper(indicativo) AND indicativo !~ '\s'),
    CONSTRAINT users_grid_formato CHECK (grid_locator IS NULL OR grid_locator ~ '^[A-R]{2}[0-9]{2}([A-X]{2})?$')
);

COMMENT ON TABLE  users                IS 'Operador: radioaficionado registrado, dueño de un libro de guardia.';
COMMENT ON COLUMN users.indicativo     IS 'Indicativo oficial (ej. HC1QRC). Único, en mayúsculas y sin espacios. No se puede cambiar.';
COMMENT ON COLUMN users.grid_locator   IS 'Localizador Maidenhead de su estación (ej. FI09). Sirve para el mapa y las distancias.';
COMMENT ON COLUMN users.foto_path      IS 'Ruta de la foto de perfil en el almacenamiento público.';
COMMENT ON COLUMN users.password       IS 'Contraseña cifrada (bcrypt). Nunca se guarda en texto plano.';


-- -----------------------------------------------------------------------------
--  2. VISIBILIDAD_PERFIL — qué datos del perfil ve el público (1 a 1 con users)
-- -----------------------------------------------------------------------------
CREATE TABLE visibilidad_perfil (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 bigint  NOT NULL,
    mostrar_nombre          boolean NOT NULL DEFAULT true,
    mostrar_pais_ciudad     boolean NOT NULL DEFAULT true,
    mostrar_equipo          boolean NOT NULL DEFAULT false,
    mostrar_biografia_foto  boolean NOT NULL DEFAULT true,
    created_at              timestamp,
    updated_at              timestamp,
    CONSTRAINT visibilidad_perfil_user_id_unique UNIQUE (user_id),
    CONSTRAINT visibilidad_perfil_user_id_foreign FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

COMMENT ON TABLE visibilidad_perfil IS 'Interruptores de "¿Qué ven los demás?". El indicativo y el país siempre son públicos; el correo y los contactos nunca.';


-- -----------------------------------------------------------------------------
--  3. BANDAS — catálogo: bandas de radioaficionados (IARU Región 2)
-- -----------------------------------------------------------------------------
CREATE TABLE bandas (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              varchar(10)    NOT NULL,
    frecuencia_min_mhz  numeric(10, 4) NOT NULL,
    frecuencia_max_mhz  numeric(10, 4) NOT NULL,
    created_at          timestamp,
    updated_at          timestamp,
    CONSTRAINT bandas_nombre_unique UNIQUE (nombre),
    CONSTRAINT bandas_rango_valido CHECK (frecuencia_min_mhz < frecuencia_max_mhz)
);

COMMENT ON TABLE bandas IS 'Catálogo de bandas. La banda de un contacto se calcula buscando en qué rango cae su frecuencia.';


-- -----------------------------------------------------------------------------
--  4. MODOS — catálogo: modos de emisión y su tipo de reporte de señal
-- -----------------------------------------------------------------------------
CREATE TABLE modos (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        varchar(10) NOT NULL,
    tipo_reporte  varchar(3)  NOT NULL,
    created_at    timestamp,
    updated_at    timestamp,
    CONSTRAINT modos_nombre_unique UNIQUE (nombre),
    CONSTRAINT modos_tipo_reporte_valido CHECK (tipo_reporte IN ('RS', 'RST', 'dB'))
);

COMMENT ON TABLE  modos              IS 'Catálogo de modos de emisión (USB, CW, FT8...).';
COMMENT ON COLUMN modos.tipo_reporte IS 'RS = voz (ej. 59), RST = telegrafía (ej. 599), dB = digitales (ej. -12).';


-- -----------------------------------------------------------------------------
--  5. PREFIJOS_PAIS — catálogo: prefijo del indicativo → país
-- -----------------------------------------------------------------------------
CREATE TABLE prefijos_pais (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prefijo     varchar(10)   NOT NULL,
    pais        varchar(100)  NOT NULL,
    codigo_bandera varchar(6),
    continente  varchar(2)    NOT NULL,
    latitud     numeric(8, 5),
    longitud    numeric(8, 5),
    created_at  timestamp,
    updated_at  timestamp,
    CONSTRAINT prefijos_pais_prefijo_unique UNIQUE (prefijo),
    CONSTRAINT prefijos_pais_continente_valido CHECK (continente IN ('NA', 'SA', 'EU', 'AF', 'AS', 'OC'))
);

COMMENT ON TABLE  prefijos_pais         IS 'Catálogo de prefijos. El país de un contacto se deduce con el prefijo MÁS LARGO que coincida (KP4 → Puerto Rico gana sobre K → Estados Unidos).';
COMMENT ON COLUMN prefijos_pais.codigo_bandera IS 'Código ISO 3166-1 alfa-2 en minúsculas (o gb-eng, gb-sct...): nombre del archivo de la bandera en public/banderas.';
COMMENT ON COLUMN prefijos_pais.latitud IS 'Coordenadas aproximadas del país (capital) para el mapa y las distancias.';


-- -----------------------------------------------------------------------------
--  6. CONTACTOS — cada QSO registrado en el libro de guardia de un operador
-- -----------------------------------------------------------------------------
CREATE TABLE contactos (
    id                            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                       bigint         NOT NULL,
    estacion_llamada              varchar(20)    NOT NULL,
    inicio_utc                    timestamp      NOT NULL,
    fin_utc                       timestamp,
    frecuencia_mhz                numeric(10, 4) NOT NULL,
    banda_id                      bigint         NOT NULL,
    modo_id                       bigint         NOT NULL,
    prefijo_pais_id               bigint,
    reporte_enviado               varchar(4)     NOT NULL,
    reporte_recibido              varchar(4)     NOT NULL,
    potencia_w                    numeric(8, 2),
    grid_locator                  varchar(8),
    nombre_operador               varchar(100),
    equipo                        varchar(255),
    activacion                    varchar(30),
    observaciones                 text,
    rechazado_por_contraparte_at  timestamp,
    created_at                    timestamp,
    updated_at                    timestamp,
    CONSTRAINT contactos_user_id_foreign         FOREIGN KEY (user_id)         REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT contactos_banda_id_foreign        FOREIGN KEY (banda_id)        REFERENCES bandas (id),
    CONSTRAINT contactos_modo_id_foreign         FOREIGN KEY (modo_id)         REFERENCES modos (id),
    CONSTRAINT contactos_prefijo_pais_id_foreign FOREIGN KEY (prefijo_pais_id) REFERENCES prefijos_pais (id) ON DELETE SET NULL,
    CONSTRAINT contactos_fin_despues_de_inicio   CHECK (fin_utc IS NULL OR fin_utc >= inicio_utc),
    CONSTRAINT contactos_frecuencia_positiva     CHECK (frecuencia_mhz > 0),
    CONSTRAINT contactos_indicativo_formato      CHECK (estacion_llamada = upper(estacion_llamada) AND estacion_llamada !~ '\s')
);

CREATE INDEX contactos_banda_id_foreign               ON contactos (banda_id);
CREATE INDEX contactos_modo_id_foreign                ON contactos (modo_id);
CREATE INDEX contactos_prefijo_pais_id_foreign        ON contactos (prefijo_pais_id);
CREATE INDEX contactos_user_id_inicio_utc_index       ON contactos (user_id, inicio_utc);
CREATE INDEX contactos_user_id_estacion_llamada_index ON contactos (user_id, estacion_llamada);

COMMENT ON TABLE  contactos                              IS 'Contacto de radio (QSO). Pertenece al libro de un solo operador. Horas siempre en UTC.';
COMMENT ON COLUMN contactos.user_id                      IS 'Dueño del libro de guardia donde está anotado el contacto.';
COMMENT ON COLUMN contactos.estacion_llamada             IS 'Indicativo de la otra estación. Si coincide con users.indicativo, permite la confirmación QSL automática y las solicitudes.';
COMMENT ON COLUMN contactos.banda_id                     IS 'Calculada automáticamente a partir de frecuencia_mhz.';
COMMENT ON COLUMN contactos.prefijo_pais_id              IS 'Calculado automáticamente a partir del prefijo de estacion_llamada.';
COMMENT ON COLUMN contactos.reporte_enviado              IS 'Reporte de señal según el modo: 59 (RS), 599 (RST) o -12 (dB).';
COMMENT ON COLUMN contactos.activacion                   IS 'Referencia POTA (ej. HC-0001) o SOTA (ej. HC/PI-001), si la hubo.';
COMMENT ON COLUMN contactos.rechazado_por_contraparte_at IS 'Fecha en que la otra estación respondió "No fui yo" a la solicitud de confirmación.';


-- -----------------------------------------------------------------------------
--  7. CONFIRMACIONES_QSL — confirmación de un contacto por cada medio
-- -----------------------------------------------------------------------------
CREATE TABLE confirmaciones_qsl (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contacto_id      bigint      NOT NULL,
    tipo             varchar(10) NOT NULL,
    enviada          boolean     NOT NULL DEFAULT false,
    fecha_envio      date,
    recibida         boolean     NOT NULL DEFAULT false,
    fecha_recepcion  date,
    created_at       timestamp,
    updated_at       timestamp,
    CONSTRAINT confirmaciones_qsl_contacto_id_foreign FOREIGN KEY (contacto_id) REFERENCES contactos (id) ON DELETE CASCADE,
    CONSTRAINT confirmaciones_qsl_contacto_id_tipo_unique UNIQUE (contacto_id, tipo),
    CONSTRAINT confirmaciones_qsl_tipo_valido CHECK (tipo IN ('tarjeta', 'eqsl', 'lotw', 'interna'))
);

COMMENT ON TABLE  confirmaciones_qsl      IS 'Confirmación QSL de un contacto. Enviada y recibida se marcan por separado. Un contacto está "confirmado" si alguna fila tiene recibida = true.';
COMMENT ON COLUMN confirmaciones_qsl.tipo IS 'tarjeta, eqsl o lotw (los marca el operador) | interna (la crea el sistema cuando ambos operadores registraron el mismo QSO).';


